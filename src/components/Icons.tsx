// Map service key to icon
export function ServiceIcon({ service, className = "w-8 h-8" }: { service: string, className?: string }) {
  switch (service) {
    case 'emergency': return <BoltIcon className={className} />
    case 'bathroom': return <HomeIcon className={className} />
    case 'boiler': case 'boilerInstall': return <FireIcon className={className} />
    case 'boiler-repair': case 'boilerRepair': return <WrenchIcon className={className} />
    case 'drain': case 'drains': return <DropletIcon className={className} />
    case 'leak': case 'leaks': return <DropletIcon className={className} />
    case 'wetroom': case 'wetRoom': return <DropletIcon className={className} />
    case 'heating': case 'centralHeating': return <FireIcon className={className} />
    case 'underfloor': return <FireIcon className={className} />
    case 'gas': case 'gasSafety': return <ShieldIcon className={className} />
    default: return <WrenchIcon className={className} />
  }
}
