  const slug = town.slug || town.name.toLowerCase().replace(/\s+/g, '-').replace(/[^a-z0-9-]/g, '')
  const c = coords[slug]
  
  if (c) {
    return { ...town, slug, lat: c.lat, lng: c.lng }
  }
  
  // For towns without coords, estimate from nearby county towns
